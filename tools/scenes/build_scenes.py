"""Render each scene as depth layers (WebP) plus overlay data for js/scene.js.

Usage: python3 tools/scenes/build_scenes.py SITE_ROOT TMP_DIR
Needs Pillow, Node and Playwright with Chromium. GitHub Actions runs this
(.github/workflows/scenes.yml) whenever a file in tools/scenes changes."""
import json, os, re, subprocess, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = sys.argv[1]
TMP = sys.argv[2]
SCENES = {'gangotri': 'gangotri.py', 'ghat': 'ghat.py'}
DROP = {'birds', 'grain'}
os.makedirs(TMP, exist_ok=True)
jobs, data = [], {}
for name, gen in SCENES.items():
    out_dir = os.path.join(SITE, 'img', 'scenes', name); os.makedirs(out_dir, exist_ok=True)
    flat = os.path.join(TMP, f'{name}-flat.svg')
    subprocess.check_call([sys.executable, os.path.join(HERE, gen), flat])
    lay = os.path.join(TMP, f'{name}-layered.svg'); js = os.path.join(TMP, f'{name}.json')
    subprocess.check_call([sys.executable, os.path.join(HERE, gen), lay, 'layered', js])
    data[name] = json.load(open(js))
    svg = open(lay).read()
    head, body = svg.split('</defs>\n', 1)
    body = body.rsplit('</svg>', 1)[0]
    parts = re.split(r'<!--LAYER (\w+)-->', body)
    layers = []
    for lname, content in zip(parts[1::2], parts[2::2]):
        if lname in DROP: continue
        p = os.path.join(TMP, f'{name}-{lname}.svg')
        open(p, 'w').write(head + '</defs>\n' + content + '</svg>\n')
        jobs.append((p, os.path.join(out_dir, f'{lname}.webp'), lname == 'sky', name, lname))
        layers.append(lname)
    jobs.append((flat, os.path.join(out_dir, 'flat.webp'), True, name, 'flat'))
    data[name]['layers'] = layers
    data[name]['art'] = [-300, 0, 2100, 800]       # the painted area, in the units overlay positions use

js_jobs = json.dumps([[j[0], j[0][:-4] + '.png'] for j in jobs])
subprocess.check_call(['node', os.path.join(HERE, 'layershot.js'), js_jobs], cwd=os.path.dirname(HERE))
HALF = {'rays', 'mist', 'sky', 'clouds'}     # soft, blurry layers lose nothing at half size
seen = {}
for svg, webp, opaque, name, lname in jobs:
    im = Image.open(svg[:-4] + '.png')
    im = im.convert('RGB') if opaque else im.convert('RGBA')
    if lname in HALF: im = im.resize((im.width // 2, im.height // 2), Image.LANCZOS)
    im.save(webp, 'WEBP', quality=80, method=6)
    blob = open(webp, 'rb').read()
    rel = os.path.relpath(webp, SITE)
    if lname != 'flat':
        if blob in seen:                 # identical to another scene's layer: reuse it
            os.remove(webp); rel = seen[blob]
        else:
            seen[blob] = rel
        data[name].setdefault('src', {})[lname] = rel
    print(f'{rel:40s} {len(blob)//1024:5d} KB')
open(os.path.join(SITE, 'js', 'scene-data.js'), 'w').write(
    '/* Generated by tools/scenes/build_scenes.py: layer list and overlay positions for each scene, in painting units. */\n'
    'window.HD_SCENES = ' + json.dumps(data, separators=(',', ':')) + ';\n')
